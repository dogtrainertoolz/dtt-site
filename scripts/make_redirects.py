 (r"pull|leash|lead|walk", "how-to-stop-your-dog-pulling-on-the-leash"),
 (r"reactiv|lunge|attack|dog-to-dog", "how-to-train-a-reactive-dog"),
 (r"aggress|bites?-its-owner|hurts-owner", "how-to-stop-your-dog-being-aggressive"),
 (r"resource-guard|guarding", "how-to-stop-resource-guarding"),
