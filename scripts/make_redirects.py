 (r"separation|alone|leave-your-dog|leaving-their-dogs", "how-do-i-stop-my-dog-getting-separation-anxiety"),
 (r"firework|scared|fear|anxi|calming", "how-to-stop-my-dog-being-scared-of-fireworks"),
