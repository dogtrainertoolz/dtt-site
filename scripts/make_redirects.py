 (r"first-(24|day|night|week)|new-puppy|puppy-setup|perfect-puppy|first-thing-i-teach|first-trick|teach-your-puppy-first|3-easy-things-to-teach-your-new-puppy|things-to-teach-your-puppy", "first-week-with-a-new-puppy"),
 (r"chew|destroy|destructive", "how-to-stop-a-puppy-chewing"),
 (r"recall|come-when-called|come-back|running-away|ignoring-you", "how-to-teach-your-dog-recall"),
